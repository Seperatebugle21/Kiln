#!/bin/bash
# Prepares what the Kiln app needs for on-device builds, from the Toolchain workflow's artifacts:
#   build/ToolchainBundle/Toolchain/     copied into Kiln.app as "Toolchain"
#     iPhoneOS.sdk.aar                   the iOS SDK without documentation, as an Apple Archive
#     resources/                         the compiler's resource directory (Clang headers, Swift shims)
#     lib/libclang_rt.ios.a              Clang's runtime helpers
#   Configuration/Toolchain.generated.xcconfig   header paths and libraries for KilnToolchainBridge.cpp
#
# Usage: Toolchain/assemble-app-toolchain.sh <llvm install dir> <swift install dir>
set -euo pipefail
LLVM="$(cd "$1" && pwd)"
SWIFT="$(cd "$2" && pwd)"
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$ROOT/build/ToolchainBundle/Toolchain"
SDK="$(xcrun --sdk iphoneos --show-sdk-path)"

rm -rf "$OUT" "$ROOT/build/SDKStaging"
mkdir -p "$OUT/lib" "$ROOT/build/SDKStaging/iPhoneOS.sdk"

echo "::group::SDK"
rsync -a \
  --exclude='*.swiftdoc' --exclude='*.swiftsourceinfo' --exclude='*.docc' --exclude='Documentation' \
  "$SDK/usr" "$SDK/System" "$SDK/SDKSettings.json" "$SDK/SDKSettings.plist" \
  "$ROOT/build/SDKStaging/iPhoneOS.sdk/"
find "$ROOT/build/SDKStaging" -type l -lname '/*' -print -delete
du -sh "$ROOT/build/SDKStaging"
# Ship the SDK as one Apple Archive that Kiln extracts on first use. As a folder, its hundreds of
# .framework directories (headers and .tbd stubs, no binaries) look like bundles to signers such
# as Feather/zsign, which then fail trying to sign them.
aa archive -d "$ROOT/build/SDKStaging" -o "$OUT/iPhoneOS.sdk.aar" -a lzfse
ls -lh "$OUT/iPhoneOS.sdk.aar"
echo "::endgroup::"

cp -R "$SWIFT/resources" "$OUT/resources"
# Clang finds SwiftShims through a module map in the resource directory itself that points into
# shims/ (Swift's build installs shims/parent.modulemap there as module.modulemap).
cp "$OUT/resources/shims/parent.modulemap" "$OUT/resources/module.modulemap"
ls "$OUT/resources"
cp "$(xcrun --sdk iphoneos clang -print-resource-dir)/lib/darwin/libclang_rt.ios.a" "$OUT/lib/"
du -sh "$OUT"

# Link flags: every static library of Swift, then LLVM/Clang/lld (ld64 resolves archives in any order).
LIBS=$(ls "$SWIFT"/lib/*.a "$LLVM"/lib/*.a | sed 's/.*/"&"/' | tr '\n' ' ')
# swift-syntax for the compiler is a set of dylibs; the Embed step in project.yml copies them into
# Kiln.app/Frameworks.
rm -rf "$ROOT/build/ToolchainFrameworks"
mkdir -p "$ROOT/build/ToolchainFrameworks"
cp "$SWIFT"/lib/host/*.dylib "$ROOT/build/ToolchainFrameworks/" 2>/dev/null || true
ls "$ROOT/build/ToolchainFrameworks"

cat > "$ROOT/Configuration/Toolchain.generated.xcconfig" <<XCCONFIG
// Generated by Toolchain/assemble-app-toolchain.sh. Do not edit or commit.
LIBRARY_SEARCH_PATHS = \$(inherited) "$SWIFT/lib/host"
HEADER_SEARCH_PATHS = \$(inherited) "$SWIFT/include" "$LLVM/include"
GCC_PREPROCESSOR_DEFINITIONS = \$(inherited) KILN_HAS_TOOLCHAIN=1
OTHER_LDFLAGS = \$(inherited) $LIBS -lc++ -lxml2
XCCONFIG
echo "Wrote Configuration/Toolchain.generated.xcconfig with $(ls "$SWIFT"/lib/*.a "$LLVM"/lib/*.a | wc -l) libraries"
