#!/bin/bash
# Prepares what the Kiln app needs for on-device builds, from the Toolchain workflow's artifacts:
#   build/ToolchainBundle/Toolchain/     copied into Kiln.app as "Toolchain"
#     SDK/iPhoneOS.sdk                   the iOS SDK without documentation
#     resources/                         the compiler's resource directory (Clang headers, Swift shims)
#     lib/libclang_rt.ios.a              Clang's runtime helpers
#   Configuration/Toolchain.generated.xcconfig   header paths and libraries for KilnToolchainBridge.cpp
#
# Usage: Toolchain/assemble-app-toolchain.sh <llvm install dir> <swift install dir>
set -euo pipefail
LLVM="$(cd "$1" && pwd)"
SWIFT="$(cd "$2" && pwd)"
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$ROOT/build/ToolchainBundle/Toolchain"
SDK="$(xcrun --sdk iphoneos --show-sdk-path)"

rm -rf "$OUT"
mkdir -p "$OUT/SDK/iPhoneOS.sdk" "$OUT/lib"

echo "::group::SDK"
rsync -a \
  --exclude='*.swiftdoc' --exclude='*.swiftsourceinfo' --exclude='*.docc' --exclude='Documentation' \
  "$SDK/usr" "$SDK/System" "$SDK/SDKSettings.json" "$SDK/SDKSettings.plist" \
  "$OUT/SDK/iPhoneOS.sdk/"
# Absolute symlinks would point outside the app bundle.
find "$OUT/SDK" -type l -lname '/*' -print -delete
du -sh "$OUT/SDK"
echo "::endgroup::"

cp -R "$SWIFT/resources" "$OUT/resources"
cp "$(xcrun --sdk iphoneos clang -print-resource-dir)/lib/darwin/libclang_rt.ios.a" "$OUT/lib/"
du -sh "$OUT"

# Link flags: every static library of Swift, then LLVM/Clang/lld (ld64 resolves archives in any order).
LIBS=$(ls "$SWIFT"/lib/*.a "$LLVM"/lib/*.a | sed 's/.*/"&"/' | tr '\n' ' ')
cat > "$ROOT/Configuration/Toolchain.generated.xcconfig" <<XCCONFIG
// Generated by Toolchain/assemble-app-toolchain.sh. Do not edit or commit.
HEADER_SEARCH_PATHS = \$(inherited) "$SWIFT/include" "$LLVM/include"
GCC_PREPROCESSOR_DEFINITIONS = \$(inherited) KILN_HAS_TOOLCHAIN=1
OTHER_LDFLAGS = \$(inherited) $LIBS -lc++ -lxml2
XCCONFIG
echo "Wrote Configuration/Toolchain.generated.xcconfig with $(ls "$SWIFT"/lib/*.a "$LLVM"/lib/*.a | wc -l) libraries"
