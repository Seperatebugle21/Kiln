import Foundation
import SwiftParser
import SwiftSyntax

/// Makes a project loadable inside Kiln.
///
/// A dylib cannot have its own `@main`, because Kiln is already running. So the generator
/// removes `@main` from the app struct and adds a file that exports `kiln_entry`, which
/// returns a `UIHostingController` showing the content of the app's `WindowGroup`.
/// The App struct's properties (such as `@State` models) are copied into that root view.
enum EntryPointGenerator {
    static let entrySymbol = "kiln_entry"
    static let generatedFileName = "__KilnEntryPoint.swift"

    enum Failure: LocalizedError {
        case noMainApp
        case noWindowGroup(String)

        var errorDescription: String? {
            switch self {
            case .noMainApp:
                return "No `@main struct …: App` was found in the project."
            case .noWindowGroup(let app):
                return "\(app).body has no `WindowGroup { … }` to show."
            }
        }
    }

    static func prepare(_ files: [SourceFile]) throws -> [SourceFile] {
        for (index, file) in files.enumerated() {
            let tree = Parser.parse(source: file.text)
            let finder = MainAppFinder()
            finder.walk(tree)
            guard let app = finder.app, let attribute = finder.mainAttribute else { continue }

            let appName = app.name.trimmedDescription
            guard let content = windowGroupContent(of: app) else {
                throw Failure.noWindowGroup(appName)
            }

            var result = files
            result[index].text = removing(attribute, from: file.text)
            result.append(SourceFile(path: generatedFileName, text: entryPointSource(members: copiedMembers(of: app), content: content)))
            return result
        }
        throw Failure.noMainApp
    }

    private static func removing(_ attribute: AttributeSyntax, from text: String) -> String {
        var bytes = Array(text.utf8)
        let start = attribute.positionAfterSkippingLeadingTrivia.utf8Offset
        let end = attribute.endPositionBeforeTrailingTrivia.utf8Offset
        guard start >= 0, end <= bytes.count, start < end else { return text }
        bytes.removeSubrange(start..<end)
        return String(decoding: bytes, as: UTF8.self)
    }

    /// The App's members except `body` and app-delegate adaptors, which have no meaning in a view.
    private static func copiedMembers(of app: StructDeclSyntax) -> [String] {
        app.memberBlock.members.compactMap { item in
            if let variable = item.decl.as(VariableDeclSyntax.self) {
                if variable.bindings.contains(where: { $0.pattern.trimmedDescription == "body" }) {
                    return nil
                }
                if variable.attributes.trimmedDescription.contains("DelegateAdaptor") {
                    return nil
                }
            }
            return item.trimmedDescription
        }
    }

    private static func windowGroupContent(of app: StructDeclSyntax) -> String? {
        let finder = WindowGroupFinder()
        finder.walk(app.memberBlock)
        return finder.content
    }

    private static func entryPointSource(members: [String], content: String) -> String {
        let memberLines = members
            .map { $0.split(separator: "\n", omittingEmptySubsequences: false).map { "    " + $0 }.joined(separator: "\n") }
            .joined(separator: "\n\n")
        let contentLines = content
            .split(separator: "\n", omittingEmptySubsequences: false)
            .map { "        " + $0 }
            .joined(separator: "\n")

        return """
        // Generated by Kiln. Do not edit.
        import SwiftUI
        import UIKit

        struct __KilnRootView: View {
        \(memberLines)

            var body: some View {
        \(contentLines)
            }
        }

        @_cdecl("\(entrySymbol)")
        public func __kilnEntry() -> UnsafeMutableRawPointer {
            let controller = UIHostingController(rootView: __KilnRootView())
            return Unmanaged.passRetained(controller).toOpaque()
        }

        """
    }
}

private final class MainAppFinder: SyntaxVisitor {
    var app: StructDeclSyntax?
    var mainAttribute: AttributeSyntax?

    init() {
        super.init(viewMode: .sourceAccurate)
    }

    override func visit(_ node: StructDeclSyntax) -> SyntaxVisitorContinueKind {
        guard app == nil else { return .skipChildren }
        for element in node.attributes {
            if case .attribute(let attribute) = element, attribute.attributeName.trimmedDescription == "main" {
                app = node
                mainAttribute = attribute
                return .skipChildren
            }
        }
        return .visitChildren
    }
}

private final class WindowGroupFinder: SyntaxVisitor {
    var content: String?

    init() {
        super.init(viewMode: .sourceAccurate)
    }

    override func visit(_ node: FunctionCallExprSyntax) -> SyntaxVisitorContinueKind {
        guard content == nil else { return .skipChildren }
        let callee = node.calledExpression.trimmedDescription
        if callee == "WindowGroup" || callee.hasPrefix("WindowGroup<"), let closure = node.trailingClosure {
            content = closure.statements.trimmedDescription
            return .skipChildren
        }
        return .visitChildren
    }
}
